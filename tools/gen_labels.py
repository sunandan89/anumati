def rows():
    for group in (RECORD_TYPES, CODES, VOICES, STATUSES, MENU, MESSAGES, SELF_SERVICE):
        yield from group


def write(lang, pick):
    seen, out = set(), []
    for key, en, hi in rows():
        value = pick(key, en, hi)
        if key in seen or not value or value == key:
            continue
        seen.add(key)
        out.append((key, value))
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, lang + ".csv"), "w", newline="", encoding="utf-8") as fh:
        csv.writer(fh, lineterminator="\n").writerows(sorted(out))
    return len(out)


